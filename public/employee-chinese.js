export function employeeText(language, arabic, english = arabic) {
  if (language === 'ar') return arabic;
  if (language !== 'zh-CN') return english;
  if (Object.hasOwn(chinese, english)) return chinese[english];
  if (Object.hasOwn(chinese, arabic)) return chinese[arabic];
  const reminder = /^Your shift (starts|ends) in (\d+) minutes$/.exec(english);
  if (reminder) return '距' + (reminder[1] === 'starts' ? '上班' : '下班') + '还有 ' + reminder[2] + ' 分钟';
  return english;
}
